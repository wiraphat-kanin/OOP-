# การเขียนโปรแกรมเชิงวัตถุเกี่ยวกับ class และ object

# class คือ ต้นแบบพิมพ์เขียว ของออบเจ็คการสร้างออบเจ็คจะต้องมีคลาสเป็นโครงสร้างต้นเเบบเสมอ

# object ทุกสิ่งที่อยู่ในไพธอนจะมองเป็นออบเจ็ค **โดยมีคุณสมบัติ 2 ประการ
# 1. คุณลักษณะ properties สิ่งที่บอกลักษระทั่วไปของวัตถุ --- คำนาม
# 2. พฤติกรรม method สิ่งที่วัตถุสามารถกระทำออกมาได้ (การกระทำ) --- คำกริยา

# การสร้างคลาสเเละออบเจ็ค
class this_is_class:
    msg = "hello world"

this_is_object = this_is_class() # การสร้าง object ของ class
print(this_is_object.msg)

